# MCP Tool: Get RCA Evidence
# ============================================================

@mcp.tool()
def get_rca_evidence() -> dict:
    """
    Return consolidated performance, transaction, failure,
    and SLA evidence for AI-powered root cause analysis.
    """

    if not os.path.exists(METRICS_FILE):
        return {
            "status": "ERROR",
            "message": "Performance metrics file was not found.",
            "file": METRICS_FILE
        }

    try:

        with open(
            METRICS_FILE,
            "r",
            encoding="utf-8"
        ) as file:

            metrics = json.load(file)

        test_summary = metrics.get(
            "test_summary",
            {}
        )

        performance = metrics.get(
            "performance_metrics",
            {}
        )

        transaction_summary = metrics.get(
            "transaction_summary",
            {}
        )

        failure_analysis = metrics.get(
            "failure_analysis",
            {}
        )

        sla = metrics.get(
            "sla",
            {}
        )

        return {
            "status": "SUCCESS",
            "evidence": {
                "test_summary": test_summary,
                "performance_metrics": performance,
                "transaction_summary": transaction_summary,
                "failure_analysis": failure_analysis,
                "sla": sla
            }
        }

    except json.JSONDecodeError as error:

        return {
            "status": "ERROR",
            "message": "metrics.json contains invalid JSON.",
            "details": str(error)
        }

    except Exception as error:

        return {
            "status": "ERROR",
            "message": "Unable to read RCA evidence.",
            "details": str(error)
        }
