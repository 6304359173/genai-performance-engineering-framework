# MCP Tool: Get Kubernetes Metrics
# ============================================================

@mcp.tool()
def get_kubernetes_metrics() -> dict:
    """
    Return current Kubernetes node and pod CPU/memory metrics
    from the Kubernetes Metrics Server.
    """

    try:
        env = os.environ.copy()

        node_result = subprocess.run(
            ["kubectl", "top", "nodes"],
            capture_output=True,
            text=True,
            env=env
        )

        pod_result = subprocess.run(
            ["kubectl", "top", "pods"],
            capture_output=True,
            text=True,
            env=env
        )

        return {
            "status": "SUCCESS" if node_result.returncode == 0 and pod_result.returncode == 0 else "ERROR",
            "source": "Kubernetes Metrics Server",
            "environment": {
                "KUBECONFIG": env.get("KUBECONFIG"),
                "PATH": env.get("PATH")
            },
            "node_return_code": node_result.returncode,
            "node_stdout": node_result.stdout.strip(),
            "node_stderr": node_result.stderr.strip(),
            "pod_return_code": pod_result.returncode,
            "pod_stdout": pod_result.stdout.strip(),
            "pod_stderr": pod_result.stderr.strip()
        }

    except Exception as error:

        return {
            "status": "ERROR",
            "message": "Unexpected error retrieving Kubernetes metrics.",
            "details": str(error)
        }
