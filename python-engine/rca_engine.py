import json
import os


# ---------------------------------------
# File locations
# ---------------------------------------

WORKSPACE = os.environ.get(
    "WORKSPACE",
    os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
)

METRICS_FILE = os.path.join(
    WORKSPACE,
    "python-engine",
    "metrics.json"
)

PROMPT_FILE = os.path.join(
    WORKSPACE,
    "ai-engine",
    "rca_prompt.txt"
)


# ---------------------------------------
# Load performance metrics
# ---------------------------------------

def load_metrics():

    if not os.path.exists(METRICS_FILE):

        raise FileNotFoundError(
            f"Metrics file not found: {METRICS_FILE}"
        )

    with open(
        METRICS_FILE,
        "r",
        encoding="utf-8"
    ) as file:

        return json.load(file)


# ---------------------------------------
# Build AI RCA prompt
# ---------------------------------------

def build_prompt(metrics):

    test_summary = metrics["test_summary"]

    performance = metrics["performance_metrics"]

    sla = metrics["sla"]

    # New throughput analysis generated by analyzer.py
    throughput = metrics.get("throughput_analysis", {})

    overall_http_rate = throughput.get(
        "overall_http_request_rate",
        performance.get("http_request_rate", 0)
    )

    overall_business_tps = throughput.get(
        "overall_business_tps",
        performance.get("tps", 0)
    )

    steady_state_tps = throughput.get(
        "steady_state_business_tps",
        performance.get("tps", 0)
    )

    steady_state_http_rate = throughput.get(
        "steady_state_http_request_rate",
        0
    )

    steady_state_window = throughput.get(
        "steady_state_window_seconds",
        0
    )

    steady_state_transactions = throughput.get(
        "steady_state_business_transactions",
        0
    )

    business_transaction_label = throughput.get(
        "business_transaction_label",
        "ProductsRequest"
    )

    http_requests_per_business_transaction = throughput.get(
        "http_requests_per_business_transaction",
        3
    )

    prompt = f"""
You are an AI assistant for a Senior Performance Engineer.

Analyze the following performance test evidence.

IMPORTANT RULES:

1. Compare actual results against the SLA.
2. Use STEADY-STATE BUSINESS TPS for the TPS SLA assessment.
3. Do not use overall TPS for the TPS SLA decision.
4. Clearly distinguish Business TPS from HTTP Request Rate.
5. Identify which SLAs passed or failed.
6. Do NOT declare a root cause without sufficient evidence.
7. Clearly separate FACTS from HYPOTHESES.
8. If evidence is insufficient, state what additional
   telemetry is required.
9. Recommend specific investigation steps.
10. Recommend possible remediation only after identifying
    the likely problem area.
11. Recommend a controlled performance retest.
12. Treat a very small SLA gap as a near-pass when appropriate,
    but keep the formal SLA result unchanged.

TEST SUMMARY
------------

Total Requests:
{test_summary["total_requests"]}

Successful Requests:
{test_summary["successful_requests"]}

Failed Requests:
{test_summary["failed_requests"]}

Test Duration:
{test_summary["test_duration_seconds"]} seconds


PERFORMANCE METRICS
-------------------

Average Response Time:
{performance["average_response_time_ms"]} ms

P90:
{performance["p90_ms"]} ms

P95:
{performance["p95_ms"]} ms

P99:
{performance["p99_ms"]} ms

Error Rate:
{performance["error_rate_percent"]}%


THROUGHPUT ANALYSIS
-------------------

Business Transaction:
{business_transaction_label}

HTTP Requests per Business Transaction:
{http_requests_per_business_transaction}

Overall HTTP Request Rate:
{overall_http_rate} req/sec

Overall Business TPS:
{overall_business_tps}

Steady-State Window:
{steady_state_window} seconds

Steady-State Business Transactions:
{steady_state_transactions}

Steady-State Business TPS:
{steady_state_tps}

Steady-State HTTP Request Rate:
{steady_state_http_rate} req/sec


SLA
---

Required P95:
{sla["required_p95_ms"]} ms

Required Business TPS:
{sla["required_tps"]}

Maximum Error Rate:
{sla["required_error_rate_percent"]}%


SLA STATUS
----------

P95:
{sla["p95_status"]}

TPS:
{sla["tps_status"]}

Error Rate:
{sla["error_rate_status"]}

Overall:
{sla["overall_status"]}


IMPORTANT TPS INTERPRETATION
----------------------------

The TPS SLA must be evaluated using:

Steady-State Business TPS:
{steady_state_tps}

Required Business TPS:
{sla["required_tps"]}

TPS Gap:
{sla["required_tps"] - steady_state_tps:.2f} TPS

The overall Business TPS of {overall_business_tps}
includes ramp-up and wind-down effects and must NOT be
used as the primary TPS SLA measurement.

The steady-state HTTP request rate of
{steady_state_http_rate} req/sec represents the three
HTTP requests executed for each business transaction.


Please provide the analysis using this structure:

1. Executive Summary

2. SLA Assessment

3. Observed Facts

4. Possible RCA Hypotheses

5. Evidence Required to Confirm RCA

6. Recommended Investigation

7. Recommended Remediation

8. Performance Retest Strategy

9. Final Engineering Conclusion
"""

    return prompt


# ---------------------------------------
# Main
# ---------------------------------------

def main():

    print("====================================")
    print(" AI Performance RCA Engine")
    print("====================================")

    metrics = load_metrics()

    prompt = build_prompt(metrics)

    with open(
        PROMPT_FILE,
        "w",
        encoding="utf-8"
    ) as file:

        file.write(prompt.strip())

    print()
    print("Performance evidence loaded successfully.")

    print()
    print("AI RCA prompt generated.")

    print()
    print("Prompt saved to:")
    print(PROMPT_FILE)


if __name__ == "__main__":
    main()